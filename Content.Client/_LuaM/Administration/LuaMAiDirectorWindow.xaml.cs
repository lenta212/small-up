    private static string BuildGenerateProcessState(
        string preset,
        int targetCount,
        bool canRunServerActions,
        bool gatewayConfigured,
        bool useGateway,
        bool requestInFlight,
        bool hasPendingConfirmation)
    {
        var presetName = GetWorkflowPresetName(preset);
        if (requestInFlight)
            return $"Generate process: disabled - request is already in flight; wait for the current AI/admin action to finish. preset={presetName}";

        if (hasPendingConfirmation)
            return $"Generate process: disabled - a server-impact action is waiting for confirm/cancel. preset={presetName}";

        if (!WorkflowAllowsGenerateProcess(preset))
            return $"Generate process: disabled - workflow preset={presetName} blocks generated server-impact processes; switch to gated-server-impact after review.";

        if (targetCount == 0)
            return $"Generate process: disabled - no valid player target is available. preset={presetName}";

        if (!canRunServerActions)
            return $"Generate process: disabled - server-impact actions are currently blocked. preset={presetName}, gatewayConfigured={gatewayConfigured}";

        var gatewayMode = gatewayConfigured && useGateway
            ? "external-gateway"
            : "local-fallback";
        return $"Generate process: ready - target available, mode={gatewayMode}, preset={presetName}; generated actions still use preview/confirmation gates.";
    }

    private static bool WorkflowAllowsQuickAction(string preset, string action)
    {
        return preset switch
        {
            WorkflowPresetReviewOnly => IsLocalReadOnlyQuickAction(action),
            WorkflowPresetLowRiskLocal => IsLocalReadOnlyQuickAction(action),
            _ => true,
        };
    }

    private static bool WorkflowAllowsRecommendationAction(string preset, bool requiresServerAction, string riskLevel)
    {
        return preset switch
        {
            WorkflowPresetReviewOnly => false,
            WorkflowPresetLowRiskLocal => !requiresServerAction &&
                                          riskLevel.Equals("low", StringComparison.OrdinalIgnoreCase),
            _ => true,
        };
    }

    private static string BuildRecommendationApplyState(
        string preset,
        string selectedAction,
        bool requiresTarget,
        bool requiresServerAction,
        string riskLevel,
        int targetCount,
        bool canRunServerActions,
        bool requestInFlight,
        bool hasPendingConfirmation)
    {
        var presetName = GetWorkflowPresetName(preset);
        var risk = string.IsNullOrWhiteSpace(riskLevel)
            ? "unknown"
            : SanitizeOutcomeCopyText(riskLevel);

        if (requestInFlight)
            return $"Apply advice: disabled - request is already in flight; wait for the current AI/admin action to finish. preset={presetName}";

        if (hasPendingConfirmation)
            return $"Apply advice: disabled - a server-impact action is waiting for confirm/cancel. preset={presetName}";

        if (string.IsNullOrWhiteSpace(selectedAction))
            return $"Apply advice: disabled - no recommendation action is selected; change the recommendation filter/sort or request fresh advice. preset={presetName}";

        if (!WorkflowAllowsRecommendationAction(preset, requiresServerAction, riskLevel))
        {
            if (preset == WorkflowPresetReviewOnly)
                return "Apply advice: disabled - workflow preset=review-only blocks all Apply advice actions; use Advice/Status/History or switch preset after review.";

            if (preset == WorkflowPresetLowRiskLocal && requiresServerAction)
                return $"Apply advice: disabled - workflow preset=low-risk-local blocks server-impact recommendations; selected risk={risk}. Switch to gated-server-impact for confirmation.";

            if (preset == WorkflowPresetLowRiskLocal)
                return $"Apply advice: disabled - workflow preset=low-risk-local only allows low-risk local recommendations; selected risk={risk}.";

            return $"Apply advice: disabled - workflow preset={presetName} blocks this recommendation.";
        }

        if (requiresTarget && targetCount == 0)
            return $"Apply advice: disabled - selected recommendation requires a target, but no valid player target is available. preset={presetName}, risk={risk}";

        if (requiresServerAction && !canRunServerActions)
            return $"Apply advice: disabled - selected recommendation requires server confirmation, but server-impact actions are currently blocked. preset={presetName}, risk={risk}";

        var mode = requiresServerAction ? "server-confirmation" : "local-safe";
        return $"Apply advice: ready - action={SanitizeOutcomeCopyText(selectedAction)}, mode={mode}, risk={risk}, preset={presetName}.";
    }

