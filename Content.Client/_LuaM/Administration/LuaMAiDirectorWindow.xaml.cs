    private static LuaMAiDirectorRecommendationEntry[] GetVisibleRecommendations(
        LuaMAiDirectorRecommendationEntry[] recommendations,
        string filter,
        string sort)
    {
        return SortRecommendations(FilterRecommendations(recommendations, filter), sort).ToArray();
    }

    private static IEnumerable<LuaMAiDirectorRecommendationEntry> FilterRecommendations(
        IEnumerable<LuaMAiDirectorRecommendationEntry> recommendations,
        string filter)
    {
        return filter switch
        {
            RecommendationFilterLowRisk => recommendations
                .Where(recommendation => IsRecommendationRisk(recommendation, "low")),
            RecommendationFilterMediumRisk => recommendations
                .Where(recommendation => IsRecommendationRisk(recommendation, "medium")),
            RecommendationFilterHighRisk => recommendations
                .Where(recommendation => IsRecommendationRisk(recommendation, "high")),
            RecommendationFilterServer => recommendations
                .Where(recommendation => recommendation.RequiresServerAction),
            RecommendationFilterSafe => recommendations
                .Where(recommendation => !recommendation.RequiresServerAction && IsRecommendationRisk(recommendation, "low")),
            RecommendationFilterTarget => recommendations
                .Where(recommendation => recommendation.RequiresTarget),
            RecommendationFilterHighConfidence => recommendations
                .Where(recommendation => recommendation.ConfidencePercent >= 75 ||
                                         recommendation.ConfidenceBand.Equals("high", StringComparison.OrdinalIgnoreCase)),
            RecommendationFilterLowConfidence => recommendations
                .Where(recommendation => recommendation.ConfidencePercent < 60 ||
                                         recommendation.ConfidenceBand.Equals("low", StringComparison.OrdinalIgnoreCase)),
            RecommendationFilterSourcePlayer => recommendations
                .Where(recommendation => RecommendationHasSourceClass(recommendation, RecommendationFilterSourcePlayer)),
            RecommendationFilterSourceSector => recommendations
                .Where(recommendation => RecommendationHasSourceClass(recommendation, RecommendationFilterSourceSector)),
            RecommendationFilterSourcePressure => recommendations
                .Where(recommendation => RecommendationHasSourceClass(recommendation, RecommendationFilterSourcePressure)),
            RecommendationFilterSourceGateway => recommendations
                .Where(recommendation => RecommendationHasSourceClass(recommendation, RecommendationFilterSourceGateway)),
            _ => recommendations,
        };
    }

    private static IEnumerable<LuaMAiDirectorRecommendationEntry> SortRecommendations(
        IEnumerable<LuaMAiDirectorRecommendationEntry> recommendations,
        string sort)
    {
        return sort switch
        {
            RecommendationSortRiskAsc => recommendations
                .OrderBy(GetRecommendationRiskWeight)
                .ThenBy(recommendation => recommendation.Priority)
                .ThenByDescending(recommendation => recommendation.ConfidencePercent),
            RecommendationSortRiskDesc => recommendations
                .OrderByDescending(GetRecommendationRiskWeight)
                .ThenBy(recommendation => recommendation.Priority)
                .ThenByDescending(recommendation => recommendation.ConfidencePercent),
            RecommendationSortConfidenceDesc => recommendations
                .OrderByDescending(recommendation => recommendation.ConfidencePercent)
                .ThenBy(GetRecommendationRiskWeight)
                .ThenBy(recommendation => recommendation.Priority),
            RecommendationSortConfidenceAsc => recommendations
                .OrderBy(recommendation => recommendation.ConfidencePercent)
                .ThenByDescending(GetRecommendationRiskWeight)
                .ThenBy(recommendation => recommendation.Priority),
            _ => recommendations
                .OrderBy(recommendation => recommendation.Priority)
                .ThenBy(GetRecommendationRiskWeight)
                .ThenByDescending(recommendation => recommendation.ConfidencePercent),
        };
    }

    private static string BuildRecommendationOverview(
        LuaMAiDirectorRecommendationEntry[] recommendations,
        int visibleCount,
        string filter,
        string sort)
    {
        var low = recommendations.Count(recommendation => IsRecommendationRisk(recommendation, "low"));
        var medium = recommendations.Count(recommendation => IsRecommendationRisk(recommendation, "medium"));
        var high = recommendations.Count(recommendation => IsRecommendationRisk(recommendation, "high"));
        var highConfidence = recommendations.Count(recommendation =>
            recommendation.ConfidencePercent >= 75 ||
            recommendation.ConfidenceBand.Equals("high", StringComparison.OrdinalIgnoreCase));
        var lowConfidence = recommendations.Count(recommendation =>
            recommendation.ConfidencePercent < 60 ||
            recommendation.ConfidenceBand.Equals("low", StringComparison.OrdinalIgnoreCase));
        var server = recommendations.Count(recommendation => recommendation.RequiresServerAction);
        var target = recommendations.Count(recommendation => recommendation.RequiresTarget);
        var topPriority = recommendations.OrderBy(recommendation => recommendation.Priority).FirstOrDefault();
        var latest = recommendations.Length == 0
            ? "none"
            : $"{topPriority!.Title}; risk={topPriority.RiskLevel}; confidence={topPriority.ConfidencePercent}%";

        var output = new StringBuilder();
        output.AppendLine($"Recommendation overview: total={recommendations.Length}, showing={visibleCount}, filter={GetRecommendationFilterName(filter)}, sort={GetRecommendationSortName(sort)}");
        output.AppendLine($"risk: low={low}, medium={medium}, high={high}");
        output.AppendLine($"confidence: high={highConfidence}, low={lowConfidence}; server={server}, target={target}");
        output.AppendLine(BuildRecommendationSourceOverview(recommendations));
        output.AppendLine($"top priority: {latest}");
        return output.ToString().TrimEnd();
    }

