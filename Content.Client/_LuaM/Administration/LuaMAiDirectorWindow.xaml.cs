    private static string BuildStatus(LuaMAiDirectorEuiState state)
    {
        var gateway = state.GatewayConfigured
            ? Loc.GetString("luam-ai-director-gateway-on")
            : Loc.GetString("luam-ai-director-gateway-off");
        var enabled = state.Enabled
            ? Loc.GetString("luam-ai-director-enabled")
            : Loc.GetString("luam-ai-director-disabled");
        var openLead = state.HasOpenRuntimeLead
            ? Loc.GetString("luam-ai-director-open-lead")
            : Loc.GetString("luam-ai-director-no-open-lead");

        var status = Loc.GetString(
            "luam-ai-director-status",
            ("enabled", enabled),
            ("gateway", gateway),
            ("players", state.ActivePlayers),
            ("runLevel", state.RunLevel),
            ("next", state.NextAttemptSeconds),
            ("pulse", state.WorldPulseEnabled ? "on" : "off"),
            ("nextPulse", state.NextWorldPulseSeconds),
            ("pressure", state.PressureSeverity),
            ("syntheticReady", state.SyntheticDevicesReady),
            ("syntheticTotal", state.SyntheticDevicesTotal),
            ("syntheticOccupied", state.SyntheticDevicesOccupied),
            ("syntheticLinked", state.SyntheticDevicesLinked),
            ("openLead", openLead));

        if (!string.IsNullOrWhiteSpace(state.AiOutcomeGroup) ||
            !string.IsNullOrWhiteSpace(state.AiOutcomeSummary))
        {
            status += "\n" + Loc.GetString(
                "luam-ai-director-ai-outcome-group",
                ("group", state.AiOutcomeGroup),
                ("summary", state.AiOutcomeSummary));
        }

        if (!string.IsNullOrWhiteSpace(state.AiOutcomeStatus))
        {
            status += "\n" + Loc.GetString(
                "luam-ai-director-ai-outcome",
                ("outcome", state.AiOutcomeStatus));
        }

        if (!string.IsNullOrWhiteSpace(state.AiBaseSummary))
        {
            status += $"\nAI base: {state.AiBaseSummary}";
        }

        if (!string.IsNullOrWhiteSpace(state.AiNextStepHint))
        {
            status += "\n" + Loc.GetString(
                "luam-ai-director-ai-next-step",
                ("hint", state.AiNextStepHint));
        }

        return status;
    }

    private static string BuildMode(LuaMAiDirectorEuiState state)
    {
        if (state.GameMasterModeEnabled)
            return Loc.GetString("luam-ai-director-mode-game-master");

        if (!state.GatewayConfigured)
            return Loc.GetString("luam-ai-director-mode-gateway-missing");

        if (state.MaxDangerEnabled)
            return Loc.GetString("luam-ai-director-mode-max-danger");

        if (state.Enabled && state.WorldPulseEnabled)
            return Loc.GetString("luam-ai-director-mode-auto-pulse");

        if (state.Enabled)
            return Loc.GetString("luam-ai-director-mode-auto");

        if (state.WorldPulseEnabled)
            return Loc.GetString("luam-ai-director-mode-manual-pulse-configured");

        return Loc.GetString("luam-ai-director-mode-safe-manual");
    }

    private static string BuildReadiness(LuaMAiDirectorEuiState state)
    {
        var status = "ready";
        if (state.RequestInFlight)
            status = "busy";
        else if (state.HasPendingConfirmation)
            status = "waiting confirmation";
        else if (!state.GatewayConfigured || !state.CanRunServerActions || IsGatewayBudgetBlocked(state))
            status = "limited";

        var output = new StringBuilder();
        output.AppendLine($"AI readiness: {status}");

        AppendReadinessLine(
            output,
            "gateway",
            state.GatewayConfigured ? "ready" : "limited",
            state.GatewayConfigured
