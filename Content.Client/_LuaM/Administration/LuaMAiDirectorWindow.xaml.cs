    private static void AppendOutcomeCopyLine(StringBuilder output, string key, string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return;

        output.AppendLine($"{key}={SanitizeOutcomeCopyText(value)}");
    }

    private static string SanitizeOutcomeCopyText(string value)
    {
        value = value.Replace('\r', ' ').Replace('\n', ' ').Trim();
        value = OutcomeCopyUrlPattern.Replace(value, "[redacted-url]");
        value = OutcomeCopySecretPattern.Replace(value, "$1=[redacted]");
        value = OutcomeCopyUuidPattern.Replace(value, "[redacted-id]");
        value = OutcomeCopyGpsPattern.Replace(value, "GPS [withheld] ");
        value = value.Trim();
        return value.Length <= OutcomeCopyLineLimit
            ? value
            : value[..OutcomeCopyLineLimit].TrimEnd();
    }

    private static string SanitizeMultilineCopyText(string value, int maxLength = AiSummaryCopyMaxLength)
    {
        if (string.IsNullOrWhiteSpace(value))
            return string.Empty;

        value = value.Replace("\r\n", "\n").Replace('\r', '\n');
        var output = new StringBuilder();

        foreach (var line in value.Split('\n'))
        {
            var sanitized = SanitizeOutcomeCopyText(line);
            var separatorLength = output.Length == 0 ? 0 : Environment.NewLine.Length;
            if (output.Length + separatorLength + sanitized.Length > maxLength)
            {
                var remaining = maxLength - output.Length - separatorLength;
                if (remaining > 0)
                {
                    if (output.Length > 0)
                        output.AppendLine();

                    output.Append(sanitized[..Math.Min(remaining, sanitized.Length)].TrimEnd());
                }

                break;
            }

            if (output.Length > 0)
                output.AppendLine();

            output.Append(sanitized);
        }

        return output.ToString().TrimEnd();
    }

