    private static string GetWorkflowTransitionRiskChange(string previousPreset, string selectedPreset)
    {
        if (previousPreset == selectedPreset)
            return "unchanged - current workflow controls remain in effect";

        if (WorkflowForcesLocal(previousPreset) && !WorkflowForcesLocal(selectedPreset))
            return "elevated - Generate, server-impact quick actions, high-risk recommendations, and gateway-backed generated process can become available";

        if (!WorkflowForcesLocal(previousPreset) && WorkflowForcesLocal(selectedPreset))
            return "tightened - generated server-impact process and server-impact quick actions are disabled by preset";

        if (previousPreset == WorkflowPresetReviewOnly && selectedPreset == WorkflowPresetLowRiskLocal)
            return "slightly expanded - low-risk non-server Apply advice can become available while server-impact remains blocked";

        if (previousPreset == WorkflowPresetLowRiskLocal && selectedPreset == WorkflowPresetReviewOnly)
            return "tightened - Apply advice is disabled and only read-only quick actions remain";

        return "changed - re-check visible action gates before acting";
    }

    private static string GetWorkflowTransitionGatewayChange(
        string previousPreset,
        string selectedPreset,
        LuaMAiDirectorEuiState state,
        bool useGateway)
    {
        if (!state.GatewayConfigured)
            return "off - API missing; generated process and review/chat cannot use external gateway";

        if (previousPreset == selectedPreset)
            return WorkflowForcesLocal(selectedPreset)
                ? "unchanged - selected preset keeps generated processes local"
                : useGateway
                    ? "unchanged - generated process may use gateway if run"
                    : "unchanged - generated process stays local while gateway checkbox is off";

        if (WorkflowForcesLocal(selectedPreset))
            return "reduced - selected preset forces generated processes local even when gateway is configured";

        return useGateway
            ? "expanded - OpenAI-compatible API can be used for generated process with minimized context"
            : "available but off - gateway is configured, but generated process remains local until checkbox is enabled";
    }

    private static string GetWorkflowTransitionServerImpactChange(
        string previousPreset,
        string selectedPreset,
        LuaMAiDirectorEuiState state)
    {
        if (state.RequestInFlight)
            return "busy - wait for the active request before using changed controls";

        if (state.HasPendingConfirmation)
            return "waiting-confirmation - resolve the pending action before using changed controls";

        if (WorkflowForcesLocal(selectedPreset))
            return "blocked-by-preset - server-impact quick actions and generated process are hidden/disabled";

        if (!state.CanRunServerActions)
            return "blocked - server-impact actions are currently disabled by server/admin gate";

        return previousPreset == selectedPreset
            ? "gated - server-impact actions still require preview, validation, confirmation, and audit history"
            : "gated-expanded - server-impact controls are visible but still require preview, validation, confirmation, and audit history";
    }

    private static string GetWorkflowTransitionNextStep(
        string previousPreset,
        string selectedPreset,
        LuaMAiDirectorEuiState state)
    {
        if (state.RequestInFlight)
            return "wait for the active AI/admin request to finish, then re-check gateway exposure";

        if (state.HasPendingConfirmation)
            return "confirm or cancel the pending action before relying on the new preset";

        if (previousPreset == selectedPreset)
            return "review Gateway exposure, Generate process, Apply advice, and recommendation risk/confidence before acting";

        if (WorkflowForcesLocal(previousPreset) && !WorkflowForcesLocal(selectedPreset))
            return "treat this as a deliberate risk increase; re-check Gateway exposure and use confirmation gates for any server-impact action";

        if (!WorkflowForcesLocal(previousPreset) && WorkflowForcesLocal(selectedPreset))
            return "continue with local advice/status/history; server-impact controls should remain blocked by preset";

        return "re-check visible disabled reasons and recommendation filters before applying AI advice";
    }

