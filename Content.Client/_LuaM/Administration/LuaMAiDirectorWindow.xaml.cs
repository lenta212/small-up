    private void RebuildRecommendationActions(LuaMAiDirectorEuiState state)
    {
        RecommendationOption.Clear();

        var selectedIndex = 0;
        var index = 0;
        var recommendations = GetVisibleRecommendations(
            state.Recommendations,
            _selectedRecommendationFilter,
            _selectedRecommendationSort);
        foreach (var recommendation in recommendations)
        {
            if (string.IsNullOrWhiteSpace(recommendation.QuickAction))
                continue;

            var label = $"P{recommendation.Priority} [{recommendation.RiskLevel}/{recommendation.ConfidenceBand} {recommendation.ConfidencePercent}%] {recommendation.Title} -> {recommendation.SuggestedAction}";
            RecommendationOption.AddItem(label, index);
            RecommendationOption.SetItemMetadata(
                index,
                new RecommendationActionMetadata(
                    recommendation.QuickAction,
                    recommendation.SuggestedAction,
                    recommendation.Title,
                    recommendation.Detail,
                    recommendation.RiskLevel,
                    recommendation.RiskReason,
                    recommendation.ConfidenceBand,
                    recommendation.ConfidencePercent,
                    recommendation.ConfidenceReason,
                    recommendation.EvidenceSummary,
                    recommendation.SourceSummary,
                    BuildRecommendationSourceClassList(recommendation),
                    recommendation.RequiresServerAction,
                    recommendation.RequiresTarget));

            if (recommendation.QuickAction == _selectedRecommendationAction)
                selectedIndex = index;

            index++;
        }

        if (RecommendationOption.ItemCount == 0)
        {
            ClearSelectedRecommendation();
            return;
        }

        RecommendationOption.Select(selectedIndex);
        UpdateSelectedRecommendation();
    }

    private void UpdateSelectedRecommendation()
    {
        if (RecommendationOption.SelectedMetadata is not RecommendationActionMetadata metadata)
        {
            ClearSelectedRecommendation();
            return;
        }

        _selectedRecommendationAction = metadata.QuickAction;
        _selectedRecommendationSuggestedAction = metadata.SuggestedAction;
        _selectedRecommendationTitle = metadata.Title;
        _selectedRecommendationDetail = metadata.Detail;
        _selectedRecommendationRiskLevel = metadata.RiskLevel;
        _selectedRecommendationRiskReason = metadata.RiskReason;
        _selectedRecommendationConfidenceBand = metadata.ConfidenceBand;
        _selectedRecommendationConfidencePercent = metadata.ConfidencePercent;
        _selectedRecommendationConfidenceReason = metadata.ConfidenceReason;
        _selectedRecommendationEvidenceSummary = metadata.EvidenceSummary;
        _selectedRecommendationSourceSummary = metadata.SourceSummary;
        _selectedRecommendationSourceClassesSummary = metadata.SourceClassesSummary;
        _selectedRecommendationRequiresServerAction = metadata.RequiresServerAction;
        _selectedRecommendationRequiresTarget = metadata.RequiresTarget;
    }

