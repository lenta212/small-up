            "ready-server-confirmation" => "local validation -> confirmation preview -> explicit Confirm; Apply advice does not execute directly",
            "ready-local-safe" => "local-safe Apply advice; no server command preview",
            _ when requiresServerAction => "blocked before confirmation; no server command preview is executable",
            _ => "blocked before local apply; no action is executable",
        };
    }

    private static string GetRecommendationExplanationStatus(
        string preset,
        string selectedAction,
        bool requiresTarget,
        bool requiresServerAction,
        string riskLevel,
        int targetCount,
        bool canRunServerActions,
        bool requestInFlight,
        bool hasPendingConfirmation)
    {
        if (requestInFlight)
            return "busy";

        if (hasPendingConfirmation)
            return "waiting-confirmation";

        if (string.IsNullOrWhiteSpace(selectedAction))
            return "no-selection";

        if (!WorkflowAllowsRecommendationAction(preset, requiresServerAction, riskLevel))
            return "blocked-by-preset";

        if (requiresTarget && targetCount == 0)
            return "blocked-missing-target";

        if (requiresServerAction && !canRunServerActions)
            return "blocked-server-gate";

        return requiresServerAction ? "ready-server-confirmation" : "ready-local-safe";
    }

    private static string GetRecommendationExplanationBlockedReason(
        string preset,
        string selectedAction,
        bool requiresTarget,
        bool requiresServerAction,
        string riskLevel,
        int targetCount,
        bool canRunServerActions,
        bool requestInFlight,
        bool hasPendingConfirmation)
    {
        if (requestInFlight)
            return "active request in flight; wait before applying advice";

        if (hasPendingConfirmation)
            return "pending confirmation must be confirmed/canceled before another AI action";

        if (string.IsNullOrWhiteSpace(selectedAction))
            return "no selected recommendation action";

        if (!WorkflowAllowsRecommendationAction(preset, requiresServerAction, riskLevel))
        {
            var presetName = GetWorkflowPresetName(preset);
            if (preset == WorkflowPresetReviewOnly)
                return "workflow preset=review-only blocks Apply advice";

            if (preset == WorkflowPresetLowRiskLocal && requiresServerAction)
                return "workflow preset=low-risk-local blocks server-impact recommendations";

            if (preset == WorkflowPresetLowRiskLocal)
                return "workflow preset=low-risk-local only allows low-risk local recommendations";

            return $"workflow preset={presetName} blocks this recommendation";
        }

        if (requiresTarget && targetCount == 0)
            return "selected recommendation requires a target but no valid target is available";

        if (requiresServerAction && !canRunServerActions)
            return "selected recommendation requires server confirmation but server-impact actions are blocked";

        return requiresServerAction
            ? "not blocked; server confirmation still required before execution"
            : "not blocked; local-safe action can be applied";
    }

