    private void ApplyWorkflowPreset(LuaMAiDirectorEuiState state, string previousPreset)
    {
        switch (_selectedWorkflowPreset)
        {
            case WorkflowPresetReviewOnly:
                UseGatewayCheck.Pressed = false;
                IgnoreOpenLeadCheck.Pressed = false;
                _selectedRecommendationFilter = RecommendationFilterSafe;
                _selectedRecommendationSort = RecommendationSortRiskAsc;
                break;
            case WorkflowPresetLowRiskLocal:
                UseGatewayCheck.Pressed = false;
                IgnoreOpenLeadCheck.Pressed = false;
                _selectedRecommendationFilter = RecommendationFilterSafe;
                _selectedRecommendationSort = RecommendationSortConfidenceDesc;
                break;
            default:
                if (state.GatewayConfigured)
                    UseGatewayCheck.Pressed = true;

                _selectedRecommendationFilter = RecommendationFilterServer;
                _selectedRecommendationSort = RecommendationSortRiskDesc;
                break;
        }

        WorkflowPresetLabel.SetMessage(BuildWorkflowPresetSummary(_selectedWorkflowPreset, state));
        RefreshWorkflowTransitionSummary(previousPreset, state);
        RefreshSafeModeSummary(state);
        RefreshGatewayExposureSummary(state);
        RefreshGenerateProcessState(state);
        RebuildRecommendationControls(state);
        RefreshRecommendationViews();
        RefreshWorkflowCopyText(state);

        var chatDisabled = state.RequestInFlight || state.HasPendingConfirmation;
        SetQuickButtonsDisabled(chatDisabled, state);
    }

