    }

    private static string GetOperationsAuditStatus(
        LuaMAiDirectorEuiState state,
        int blockTotal,
        int gatewayStopTotal,
        ActionHistorySummary history)
    {
        if (state.RequestInFlight)
            return "busy";

        if (state.HasPendingConfirmation)
            return "waiting approval";

        if (!state.CanRunServerActions)
            return "server actions blocked";

        if (IsGatewayBudgetBlocked(state) || blockTotal > 0 || gatewayStopTotal > 0 || history.Blocked > 0)
            return "watch";

        if (history.Total > 0 || state.ReviewHistoryCount > 0)
            return "recorded";

        return "clear";
    }

    private static string BuildRoundAuditFooter(LuaMAiDirectorEuiState state)
    {
        var history = BuildActionHistorySummary(state.AiActionHistory);
        var blockTotal = state.GatewayBlockUnsafeInputs +
                         state.GatewayBlockBudgets +
                         state.GatewayBlockInvalidSchemas +
                         state.GatewayBlockForbiddenActions +
                         state.GatewayBlockLocalValidations;
        var gatewayStopTotal = state.GatewayAuditUnsafeInputBlocks +
                               state.GatewayAuditBudgetBlocks +
                               state.GatewayAuditProviderOutputBlocks +
                               state.GatewayAuditTransportFailures;
        var status = GetOperationsAuditStatus(state, blockTotal, gatewayStopTotal, history);
        var budget = IsGatewayBudgetBlocked(state)
            ? $"blocked retrySeconds={state.GatewayBudgetRetrySeconds}"
            : $"ready windowRemaining={state.GatewayBudgetWindowRemaining}, roundRemaining={state.GatewayBudgetRoundRemaining}";

        var output = new StringBuilder();
        output.AppendLine($"AI round audit footer: {status}");
        output.AppendLine($"gate={GetRoundAuditGate(state)}; pending={state.HasPendingConfirmation}; budget={budget}; stops={gatewayStopTotal}; blocks={blockTotal}");
        output.AppendLine($"lastDecision={BuildRoundAuditLastDecision(state.AiActionHistory)}");
        output.AppendLine($"lastBlock={BuildRoundAuditLastBlock(state)}");
        output.AppendLine($"next={BuildRoundAuditNextStep(state)}");
        return output.ToString().TrimEnd();
    }

    private static string GetRoundAuditGate(LuaMAiDirectorEuiState state)
    {
        if (state.RequestInFlight)
            return "busy";

        if (state.GameMasterModeEnabled)
            return "game-master";

        if (state.HasPendingConfirmation)
            return "waiting-approval";

        if (!state.CanRunServerActions)
            return "server-actions-blocked";

        return state.GatewayConfigured ? "open" : "local-only";
    }

    private static string BuildRoundAuditLastDecision(string history)
    {
        var entries = ParseActionHistoryEntries(history);
        if (entries.Length == 0)
            return "none";

        var latest = entries[0];
        var decision = string.IsNullOrWhiteSpace(latest.Decision) ? "unknown" : SanitizeOutcomeCopyText(latest.Decision);
        var action = string.IsNullOrWhiteSpace(latest.Action) ? "unknown" : SanitizeOutcomeCopyText(latest.Action);
        var impact = string.IsNullOrWhiteSpace(latest.Impact) ? "unknown" : SanitizeOutcomeCopyText(latest.Impact);
        var result = string.IsNullOrWhiteSpace(latest.Result)
            ? "no result"
            : SanitizeOperationsAuditDetail(latest.Result);

        return $"decision={decision}, action={action}, impact={impact}, result={result}";
    }

    private static string BuildRoundAuditLastBlock(LuaMAiDirectorEuiState state)
    {
        if (state.GatewayBlockReasonSummary.Length > 0)
            return $"recent - {SanitizeOperationsAuditDetail(state.GatewayBlockReasonSummary[0])}";

        if (state.GatewayBlockLocalValidations > 0)
            return $"local-validation count={state.GatewayBlockLocalValidations}";

        if (state.GatewayBlockForbiddenActions > 0)
            return $"forbidden-action count={state.GatewayBlockForbiddenActions}";

        if (state.GatewayBlockInvalidSchemas > 0)
            return $"invalid-schema count={state.GatewayBlockInvalidSchemas}";

        if (state.GatewayBlockBudgets > 0 || state.GatewayAuditBudgetBlocks > 0 || IsGatewayBudgetBlocked(state))
            return $"budget count={state.GatewayBlockBudgets + state.GatewayAuditBudgetBlocks}, retrySeconds={state.GatewayBudgetRetrySeconds}";

        if (state.GatewayBlockUnsafeInputs > 0 || state.GatewayAuditUnsafeInputBlocks > 0)
            return $"unsafe-input count={state.GatewayBlockUnsafeInputs + state.GatewayAuditUnsafeInputBlocks}";

        if (state.GatewayAuditProviderOutputBlocks > 0)
            return $"provider-output count={state.GatewayAuditProviderOutputBlocks}";

        if (state.GatewayAuditTransportFailures > 0)
            return $"transport count={state.GatewayAuditTransportFailures}";

        return "none";
    }

    private static string BuildRoundAuditNextStep(LuaMAiDirectorEuiState state)
    {
        if (!string.IsNullOrWhiteSpace(state.AiNextStepHint))
            return SanitizeOperationsAuditDetail(state.AiNextStepHint);

        if (state.HasPendingConfirmation)
            return "confirm or cancel the pending action before sending more AI commands";

        if (IsGatewayBudgetBlocked(state))
            return "wait for gateway budget retry or use local status/review-only controls";

        if (!state.CanRunServerActions)
            return "server-impact actions are blocked; use local status or review-only controls";

        return "review recommendations, action history, and risk/confidence before applying AI advice";
    }

