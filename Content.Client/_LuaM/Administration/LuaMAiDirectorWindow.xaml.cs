    public void SetState(LuaMAiDirectorEuiState state)
    {
        _currentState = state;
        _enabled = state.Enabled;
        ToggleButton.Text = Loc.GetString(state.Enabled
            ? "luam-ai-director-disable"
            : "luam-ai-director-enable");

        StatusLabel.SetMessage(BuildStatus(state));
        ModeLabel.SetMessage(BuildMode(state));
        WorkflowPresetLabel.SetMessage(BuildWorkflowPresetSummary(_selectedWorkflowPreset, state));
