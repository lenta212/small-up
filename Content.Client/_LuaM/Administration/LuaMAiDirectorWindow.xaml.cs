    private static string BuildActionHistoryDisplayBody(string history, string filter)
    {
        var entries = ParseActionHistoryEntries(history);
        var filtered = FilterActionHistoryEntries(entries, filter);
        var visibleHistory = filtered.Length == 0
            ? "No action decisions match this filter."
            : string.Join("\n\n---\n\n", filtered.Select(entry => entry.Raw));
        return $"{BuildActionHistoryOverview(entries, filtered.Length, filter)}\n\n{visibleHistory}";
    }

    private static ActionHistoryEntry[] ParseActionHistoryEntries(string history)
    {
        history = history.Replace("\r\n", "\n").Replace('\r', '\n');
        var chunks = history.Split(
            "\n\n---\n\n",
            StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        var entries = new List<ActionHistoryEntry>();

        foreach (var chunk in chunks)
        {
            var raw = chunk.Trim();
            if (string.IsNullOrWhiteSpace(raw))
                continue;

            entries.Add(ParseActionHistoryEntry(raw));
        }

        return entries.ToArray();
    }

    private static ActionHistoryEntry ParseActionHistoryEntry(string raw)
    {
        var header = raw.Split('\n', 2, StringSplitOptions.TrimEntries)[0];
        var decision = ReadActionHistoryField(raw, "- decision=");
        var action = ReadActionHistoryField(raw, "- action=");
        var title = ReadActionHistoryField(raw, "- title=");
        var impact = ReadActionHistoryField(raw, "- impact=");
        var result = ReadActionHistoryField(raw, "- result=");
        var preview = ReadActionHistoryField(raw, "- preview=");
        var searchable = $"{action}\n{title}\n{result}\n{preview}";
        var usesGateway = ContainsActionHistoryText(searchable, "gateway") ||
                          ContainsActionHistoryText(searchable, "provider") ||
                          ContainsActionHistoryText(searchable, "usegateway=true");
        var serverImpact = IsServerImpactAction(action, impact);
        var blocked = ContainsActionHistoryText(result, "blocked") ||
                      ContainsActionHistoryText(result, "refused") ||
                      ContainsActionHistoryText(result, "failed") ||
                      ContainsActionHistoryText(result, "rejected") ||
                      ContainsActionHistoryText(result, "validation") ||
                      ContainsActionHistoryText(result, "did not run") ||
                      ContainsActionHistoryText(result, "no action ran");
        var localSafe = !serverImpact ||
                        IsReadOnlyAction(action) ||
                        ContainsActionHistoryText(result, "no server effect");

        return new ActionHistoryEntry(
            raw,
            header,
            decision,
            action,
            title,
            impact,
            result,
            usesGateway,
            serverImpact,
            localSafe,
            blocked);
    }

    private static string ReadActionHistoryField(string raw, string prefix)
    {
        foreach (var line in raw.Split('\n', StringSplitOptions.TrimEntries))
        {
            if (line.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
                return line[prefix.Length..].Trim();
        }

        return string.Empty;
    }

    private static bool ContainsActionHistoryText(string value, string text)
    {
        return value.Contains(text, StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsServerImpactAction(string action, string impact)
    {
        return impact.Equals("High", StringComparison.OrdinalIgnoreCase) ||
               impact.Equals("Medium", StringComparison.OrdinalIgnoreCase) ||
               action.Equals("generate-process", StringComparison.OrdinalIgnoreCase) ||
               action.StartsWith("quick:", StringComparison.OrdinalIgnoreCase) &&
               !IsReadOnlyAction(action);
    }

    private static bool IsReadOnlyAction(string action)
    {
        return action.Equals($"quick:{LuaMAiDirectorEuiMsg.QuickRecommendations}", StringComparison.OrdinalIgnoreCase) ||
               action.Equals($"quick:{LuaMAiDirectorEuiMsg.QuickStatus}", StringComparison.OrdinalIgnoreCase) ||
               action.Equals($"quick:{LuaMAiDirectorEuiMsg.QuickHistory}", StringComparison.OrdinalIgnoreCase);
    }

    private static ActionHistoryEntry[] FilterActionHistoryEntries(ActionHistoryEntry[] entries, string filter)
    {
        return filter switch
        {
            ActionHistoryFilterRecent => entries.Take(ActionHistoryRecentLimit).ToArray(),
            ActionHistoryFilterConfirmed => entries
                .Where(entry => entry.Decision.Equals("confirmed", StringComparison.OrdinalIgnoreCase))
                .ToArray(),
            ActionHistoryFilterCanceled => entries
                .Where(entry => entry.Decision.Equals("canceled", StringComparison.OrdinalIgnoreCase))
                .ToArray(),
            ActionHistoryFilterBlocked => entries
                .Where(entry => entry.Blocked)
                .ToArray(),
            ActionHistoryFilterGateway => entries
                .Where(entry => entry.UsesGateway)
                .ToArray(),
            ActionHistoryFilterServer => entries
                .Where(entry => entry.ServerImpact)
                .ToArray(),
            ActionHistoryFilterLocal => entries
                .Where(entry => entry.LocalSafe)
                .ToArray(),
            _ => entries,
        };
    }

    private static string BuildActionHistoryOverview(ActionHistoryEntry[] entries, int visibleCount, string filter)
    {
        var confirmed = entries.Count(entry => entry.Decision.Equals("confirmed", StringComparison.OrdinalIgnoreCase));
        var canceled = entries.Count(entry => entry.Decision.Equals("canceled", StringComparison.OrdinalIgnoreCase));
        var blocked = entries.Count(entry => entry.Blocked);
        var gateway = entries.Count(entry => entry.UsesGateway);
        var server = entries.Count(entry => entry.ServerImpact);
        var local = entries.Count(entry => entry.LocalSafe);
        var latest = entries.Length == 0
            ? "none"
            : $"{entries[0].Header}; decision={entries[0].Decision}; action={entries[0].Action}; impact={entries[0].Impact}";

        var output = new StringBuilder();
        output.AppendLine($"Action history overview: total={entries.Length}, showing={visibleCount}, filter={GetActionHistoryFilterName(filter)}");
        output.AppendLine($"decisions: confirmed={confirmed}, canceled={canceled}, blocked={blocked}");
        output.AppendLine($"source/scope: gateway={gateway}, server-impact={server}, local-safe={local}");
        output.AppendLine($"latest: {latest}");
        return output.ToString().TrimEnd();
    }

