    private static bool IsGatewayBudgetBlocked(LuaMAiDirectorEuiState state)
    {
        if (!state.GatewayConfigured)
            return false;

        if (state.GatewayBudgetRetrySeconds > 0)
            return true;

        return state.GatewayBudgetWindowLimit > 0 && state.GatewayBudgetWindowRemaining <= 0 ||
               state.GatewayBudgetRoundLimit > 0 && state.GatewayBudgetRoundRemaining <= 0;
    }

