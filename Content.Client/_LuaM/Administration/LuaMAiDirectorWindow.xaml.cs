    private static string BuildAuditBundleRecommendationSection(
        LuaMAiDirectorEuiState state,
        string filter,
        string sort)
    {
        if (state.Recommendations.Length == 0)
            return "No local AI recommendations are available; use Status or Review impact before enabling server-impact commands.";

        var visible = GetVisibleRecommendations(state.Recommendations, filter, sort);
        var output = new StringBuilder();
        output.AppendLine($"filter={GetRecommendationFilterName(filter)}; sort={GetRecommendationSortName(sort)}; total={state.Recommendations.Length}; showing={visible.Length}");
        output.AppendLine(BuildRecommendationOverview(state.Recommendations, visible.Length, filter, sort));

        if (visible.Length == 0)
        {
            output.AppendLine(BuildRecommendationEmptyStateHint(state.Recommendations, filter, sort));
            return output.ToString().TrimEnd();
        }

        output.AppendLine("top visible recommendations:");
        foreach (var recommendation in visible.Take(3))
        {
            output.AppendLine(
                $"- P{recommendation.Priority} risk={recommendation.RiskLevel} confidence={recommendation.ConfidenceBand}/{recommendation.ConfidencePercent}% server={recommendation.RequiresServerAction} target={recommendation.RequiresTarget} action={recommendation.SuggestedAction}");
            output.AppendLine($"  title={recommendation.Title}");
            output.AppendLine($"  why={recommendation.RiskReason}; confidenceReason={recommendation.ConfidenceReason}");
            output.AppendLine($"  evidence={recommendation.EvidenceSummary}; source={recommendation.SourceSummary}");
        }

        if (visible.Length > 3)
            output.AppendLine($"truncated={visible.Length - 3} additional visible recommendations omitted from compact audit bundle");

        return output.ToString().TrimEnd();
    }

    private static string BuildAuditBundleActionHistorySection(
        LuaMAiDirectorEuiState state,
        string filter)
    {
        if (string.IsNullOrWhiteSpace(state.AiActionHistory))
            return "No AI action history is recorded.";

        var entries = ParseActionHistoryEntries(state.AiActionHistory);
        var filtered = FilterActionHistoryEntries(entries, filter);
        var output = new StringBuilder();
        output.AppendLine($"filter={GetActionHistoryFilterName(filter)}; saved={state.AiActionHistoryCount}");
        output.AppendLine(BuildActionHistoryOverview(entries, filtered.Length, filter));

        if (filtered.Length == 0)
        {
            output.AppendLine("No action decisions match this filter.");
            return output.ToString().TrimEnd();
        }

        output.AppendLine("latest matching decisions:");
        foreach (var entry in filtered.Take(3))
            output.AppendLine($"- decision={entry.Decision}; action={entry.Action}; impact={entry.Impact}; result={entry.Result}");

        if (filtered.Length > 3)
            output.AppendLine($"truncated={filtered.Length - 3} additional matching decisions omitted from compact audit bundle");

        return output.ToString().TrimEnd();
    }

    private static string GetSafeModeStatus(string preset, LuaMAiDirectorEuiState state, bool useGateway)
    {
        if (state.RequestInFlight)
            return "busy";

        if (state.GameMasterModeEnabled)
            return "game-master";

        if (state.HasPendingConfirmation)
            return "waiting-confirmation";

        if (!state.GatewayConfigured)
            return "local-only";

        if (WorkflowForcesLocal(preset) || !useGateway)
            return "preset-local";

        if (!state.CanRunServerActions)
            return "server-blocked";

        return "gated";
    }

