    private static string BuildRecommendationSourceClassList(LuaMAiDirectorRecommendationEntry recommendation)
    {
        return recommendation.SourceClasses is { Length: > 0 }
            ? string.Join(",", recommendation.SourceClasses)
            : "fallback-text";
    }

    private static string BuildRecommendationSourceClassCheck(
        string evidenceSummary,
        string sourceSummary,
        string sourceClassesSummary)
    {
        var explicitClasses = ParseRecommendationSourceClasses(sourceClassesSummary);
        var textClasses = InferRecommendationSourceClassesFromText(sourceSummary, evidenceSummary);

        if (explicitClasses.Length == 0)
            return "source check: fallback-text - explicit SourceClasses unavailable; verify source/evidence text before applying";

        var explicitList = string.Join(",", explicitClasses);
        if (textClasses.Length == 0)
            return $"source check: explicit-only - SourceClasses={explicitList}; no source/evidence class cues matched; verify evidence before applying";

        var textList = string.Join(",", textClasses);
        if (explicitClasses.Length == textClasses.Length &&
            explicitClasses.All(explicitClass => textClasses.Contains(explicitClass, StringComparer.OrdinalIgnoreCase)))
        {
            return $"source check: aligned - SourceClasses match source/evidence cues ({explicitList})";
        }

        var hasOverlap = explicitClasses.Any(explicitClass =>
            textClasses.Contains(explicitClass, StringComparer.OrdinalIgnoreCase));
        return hasOverlap
            ? $"source check: warning-partial - SourceClasses={explicitList}; textCues={textList}; verify source evidence before applying"
            : $"source check: warning-mismatch - SourceClasses={explicitList}; textCues={textList}; review evidence before applying";
    }

    private static bool IsRecommendationSourceClassCheckWarning(string sourceClassCheck)
    {
        return sourceClassCheck.Contains("warning-", StringComparison.OrdinalIgnoreCase) ||
               sourceClassCheck.Contains("fallback-text", StringComparison.OrdinalIgnoreCase) ||
               sourceClassCheck.Contains("explicit-only", StringComparison.OrdinalIgnoreCase);
    }

    private static string[] ParseRecommendationSourceClasses(string sourceClassesSummary)
    {
        if (string.IsNullOrWhiteSpace(sourceClassesSummary) ||
            sourceClassesSummary.Equals("fallback-text", StringComparison.OrdinalIgnoreCase))
        {
            return [];
        }

        var tokens = sourceClassesSummary.Split(
            [',', ';', '|', ' '],
            StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
        var sourceClasses = new List<string>();
        foreach (var token in tokens)
        {
            var sourceClass = RecommendationSourceClassOrder.FirstOrDefault(candidate =>
                candidate.Equals(token, StringComparison.OrdinalIgnoreCase));
            if (!string.IsNullOrWhiteSpace(sourceClass) &&
                !sourceClasses.Contains(sourceClass, StringComparer.OrdinalIgnoreCase))
            {
                sourceClasses.Add(sourceClass);
            }
        }

        return sourceClasses.ToArray();
    }

    private static string[] InferRecommendationSourceClassesFromText(string sourceSummary, string evidenceSummary)
    {
        return RecommendationSourceClassOrder
            .Where(sourceClass => RecommendationTextMatchesSourceClass(sourceSummary, evidenceSummary, sourceClass))
            .ToArray();
    }

    private static bool RecommendationHasSourceClass(
        LuaMAiDirectorRecommendationEntry recommendation,
        string sourceClass)
    {
        var explicitSourceClass = GetRecommendationSourceClassValue(sourceClass);
        if (!string.IsNullOrWhiteSpace(explicitSourceClass) &&
            recommendation.SourceClasses is { Length: > 0 })
        {
            return recommendation.SourceClasses.Any(candidate =>
                candidate.Equals(explicitSourceClass, StringComparison.OrdinalIgnoreCase));
        }

        return sourceClass switch
        {
            RecommendationFilterSourcePlayer =>
                recommendation.RequiresTarget ||
                RecommendationTextMatchesSourceClass(
                    recommendation.SourceSummary,
                    recommendation.EvidenceSummary,
                    sourceClass),
            RecommendationFilterSourceSector or
            RecommendationFilterSourcePressure or
            RecommendationFilterSourceGateway =>
                RecommendationTextMatchesSourceClass(
                    recommendation.SourceSummary,
                    recommendation.EvidenceSummary,
                    sourceClass),
            _ => false,
        };
    }

    private static bool RecommendationTextMatchesSourceClass(
        string sourceSummary,
        string evidenceSummary,
        string sourceClass)
    {
        var filter = GetRecommendationSourceClassFilter(sourceClass);
        return filter switch
        {
            RecommendationFilterSourcePlayer =>
                RecommendationTextContainsAny(
                    sourceSummary,
                    "player",
                    "session",
                    "target",
                    "personal") ||
                RecommendationTextContainsAny(
                    evidenceSummary,
                    "target=",
                    "target required",
                    "requiredTarget"),
            RecommendationFilterSourceSector =>
                RecommendationTextContainsAny(
                    sourceSummary,
                    "sector",
                    "story",
                    "history",
                    "lead",
                    "reputation") ||
                RecommendationTextContainsAny(
                    evidenceSummary,
                    "openLead=",
                    "recentHistory=",
                    "lockedLead",
                    "reputation"),
            RecommendationFilterSourcePressure =>
                RecommendationTextContainsAny(
                    sourceSummary,
                    "condition",
                    "hazard",
                    "pressure",
                    "danger",
                    "synthetic") ||
                RecommendationTextContainsAny(
                    evidenceSummary,
                    "activeCondition=",
                    "activeConditions=",
                    "unresolvedHazard",
                    "maxDanger=",
                    "pressureSeverity=",
                    "syntheticsReady="),
            RecommendationFilterSourceGateway =>
                RecommendationTextContainsAny(
                    sourceSummary,
                    "gateway",
                    "config",
                    "provider") ||
                RecommendationTextContainsAny(
                    evidenceSummary,
                    "gatewayConfigured=",
                    "provider",
                    "route="),
            _ => false,
        };
    }

    private static bool RecommendationTextContainsAny(string text, params string[] tokens)
    {
        return tokens.Any(token => text.Contains(token, StringComparison.OrdinalIgnoreCase));
    }

