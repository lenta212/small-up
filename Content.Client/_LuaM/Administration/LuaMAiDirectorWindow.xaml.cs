        OperationsAuditLabel.SetMessage(BuildOperationsAudit(state));
        ConditionsLabel.SetMessage(BuildConditions(state));
        ResultLabel.SetMessage(BuildResult(state));
        _lastReview = state.LastReview;
        _lastOutcomeCopyText = BuildOutcomeCopyText(state);
        ReviewHistoryLabel.SetMessage(BuildReviewHistory(state));
        RebuildActionHistoryFilters(state);
        _lastActionHistoryCopyText = BuildActionHistoryCopyText(state, _selectedActionHistoryFilter);
        ActionHistoryLabel.SetMessage(BuildActionHistory(state, _selectedActionHistoryFilter));
        RoundAuditFooterLabel.SetMessage(BuildRoundAuditFooter(state));
        ChatLabel.SetMessage(state.ChatTranscript);
        _pendingConfirmationId = state.PendingConfirmationId;
        ConfirmationPanel.Visible = state.HasPendingConfirmation;
        ConfirmationLabel.SetMessage(BuildConfirmation(state));
        RebuildPlayers(state);
        RebuildTemplates(state);
        RebuildGatewayShips(state);
        RebuildRecommendationControls(state);
        RefreshRecommendationViews();

        var chatDisabled = state.RequestInFlight || state.HasPendingConfirmation;
        var serverActionDisabled = chatDisabled || !state.CanRunServerActions;
        var workflowForcesLocal = WorkflowForcesLocal(_selectedWorkflowPreset);
        if (workflowForcesLocal)
            UseGatewayCheck.Pressed = false;

        RefreshWorkflowTransitionSummary(_selectedWorkflowPreset, state);
        RefreshSafeModeSummary(state);
        RefreshGatewayExposureSummary(state);
        RefreshWorkflowCopyText(state);
        RefreshAuditBundleCopyText(state);
        GenerateButton.Disabled = serverActionDisabled ||
                                  !WorkflowAllowsGenerateProcess(_selectedWorkflowPreset) ||
                                  TargetOption.ItemCount == 0;
        RefreshGenerateProcessState(state);
        CapabilityButton.Disabled = state.RequestInFlight;
        ChatButton.Disabled = chatDisabled;
        ChatInput.Editable = !chatDisabled;
        SetQuickButtonsDisabled(chatDisabled, state);
        UseGatewayCheck.Disabled = !state.GatewayConfigured || state.RequestInFlight || workflowForcesLocal;
        IgnoreOpenLeadCheck.Disabled = state.RequestInFlight;
        RefreshButton.Disabled = state.RequestInFlight;
        ToggleButton.Disabled = serverActionDisabled;
        ReviewButton.Disabled = state.RequestInFlight || !state.GatewayConfigured;
        CopyOutcomeButton.Disabled = string.IsNullOrWhiteSpace(_lastOutcomeCopyText);
        CopyWorkflowSummaryButton.Disabled = string.IsNullOrWhiteSpace(_lastWorkflowCopyText);
        CopyAuditBundleButton.Disabled = string.IsNullOrWhiteSpace(_lastAuditBundleCopyText);
        CopyReviewButton.Disabled = string.IsNullOrWhiteSpace(state.LastReview);
        CopyActionHistoryButton.Disabled = string.IsNullOrWhiteSpace(_lastActionHistoryCopyText);
        LogReviewButton.Disabled = state.RequestInFlight || string.IsNullOrWhiteSpace(state.LastReview);
        ConfirmActionButton.Disabled = state.RequestInFlight || !state.HasPendingConfirmation || !state.CanRunServerActions;
        CancelActionButton.Disabled = state.RequestInFlight || !state.HasPendingConfirmation;
        UpdateRecommendationApplyButton(chatDisabled, state);
    }

    private void SubmitChat()
    {
        var message = ChatInput.Text.Trim();
        if (string.IsNullOrWhiteSpace(message))
            return;

        SubmitChatText(message);
        ChatInput.Clear();
    }

